def test_build_on_an_unconfigured_tree_takes_the_standalone_escape(tmp_path,
                                                                   monkeypatch):
    """On an unconfigured tree a build opt-in builds `-f standalone.mk native`
    for the DIAG helper -- but only where standalone.mk exists, so the
    guarantee "never invoke make where it cannot work" still holds for a tree
    without one (tested above)."""
    _clear_role_env(monkeypatch)
    clone = _unconfigured_clone(tmp_path, monkeypatch)
    (clone / "capture_cell_diag" / "standalone.mk").write_text("native:\n")
    calls = []

    def fake_build(clone_, target, subdir="capture_cell_diag", makefile=None):
        calls.append((target, subdir, makefile))
        _exe(clone_ / subdir / "build-native" / "kismet_cap_cell_diag")
        return True, ""

    monkeypatch.setattr(cb, "_build", fake_build)
    found = cb.discover("celldiag", allow_build=True)
    assert calls == [("native", "capture_cell_diag", "standalone.mk")]
    assert found.status == "built", found
    assert found.path.parent.name == "build-native"


@pytest.mark.parametrize("bdir_name,target",
                         [("build-native", "native"), ("build-baseline", "baseline")])
def test_a_standalone_binary_takes_its_closure_from_the_parent_standalone_mk(
        tmp_path, bdir_name, target):
    """The narrow-to-empty direction. A build-native/ (or build-baseline/)
    binary's closure must not be derived from that directory itself: there is
    no makefile there, so the glob fallback finds only generated files, and a
    source edit would leave the binary reading "current"."""
    src = tmp_path / "capture_cell_diag"
    bdir = src / bdir_name
    bdir.mkdir(parents=True)
    (tmp_path / "fw.c").write_text("")
    (tmp_path / "fw.h").write_text("")
    for name in ("a.c", "a.h", "b.inc"):
        (src / name).write_text("")
    (bdir / "config.h").write_text("")
    (src / "standalone.mk").write_text(
        f"OUT_DIR = {bdir_name}\n"
        "OUT_BIN = $(OUT_DIR)/kismet_cap_cell_diag\n"
        "SRCS = a.c\n"
        "$(OUT_BIN): guard $(OUT_DIR)/config.h $(SRCS) ../fw.c ../fw.h\n"
        "\tcc -o $@ $(SRCS)\n")
    binary = _exe(bdir / "kismet_cap_cell_diag")

    deps = cb.link_dependencies(binary)
    assert deps.mode == "derived", deps.note
    names = {p.name for p in deps.sources}
    assert {"a.c", "fw.c", "fw.h", "config.h"} <= names, names
    assert {"a.h", "b.inc"} <= names, \
        "the rule names no headers: the directory's headers must be added"
    assert deps.makefile == src / "standalone.mk"

    st = cb.Staleness("celldiag", binary, (), deps)
    assert st.rebuild_cmd() == f"make -C {src} -f standalone.mk {target}"


def test_the_cellat_baseline_mirrors_monitor_objs():
    """The cellat `baseline` compiles a hand-kept copy of Makefile.in's
    MONITOR_OBJS. A module added there and not here can still link (its caller
    may sit behind a runtime branch) while silently dropping a capability."""
    clone = cb.tree_root()
