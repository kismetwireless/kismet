"""Discovery + skip-reason contract for the capture-binary harnesses.

A skipped harness and a passing one must not produce the same silence:
something has to say whether the compiled binary was exercised. These tests
pin the two properties that guarantee that (see ``cell_binaries``):

1. **Discovery works with no environment at all** -- the common case (you built
   the tree, then ran the tests) needs nothing exported, so "nobody set the env
   var" stops being a reason a binary goes untested.
2. **The skip reasons are distinguishable** -- "this is not a source tree"
   (a fact about where you are pointed) never renders as the same string as
   "the sources are here and nobody built the binary" (a fact about nobody
   having run it).

Property 2 is tested by pointing discovery at synthetic directories under
``tmp_path``, so it holds whatever state the real tree is in.
"""
from __future__ import annotations

import re
from pathlib import Path

import pytest

import cell_binaries as cb


def test_every_role_names_its_env_var_and_make_target():
    """The make targets live in ``ROLES``, not only in a harness docstring, so
    a command like `make -C capture_cell_diag logstream-dump` is discoverable
    where a reader of the harness would look."""
    assert set(cb.ROLES) == {"celldiag", "logstream", "cellat"}
    for role, (env_var, rel, target) in cb.ROLES.items():
        assert env_var.startswith("KP_") and env_var.endswith("_BIN")
        # Roles do not all live in one subdirectory (cellat is in a different
        # one), so do not assert a fixed prefix. The property actually needed
        # is that the make target is the binary's basename, so
        # `_subdir_for(rel)` + target is a build command for any subdirectory.
        subdir, _, base = rel.partition("/")
        assert subdir.startswith("capture_cell_") and base
        assert target


def test_absent_tree_and_unbuilt_driver_are_DIFFERENT_statuses(tmp_path, monkeypatch):
    """Both are skips; they must never be the same skip.

    Being pointed at something that is not a source tree is benign. An unbuilt
    binary in a tree that IS here is the finding, because it means the binary
    could have been exercised and was not."""
    for env_var, _, _ in cb.ROLES.values():
        monkeypatch.delenv(env_var, raising=False)
    monkeypatch.delenv("KP_CELL_BUILD", raising=False)

    # (a) not a source tree at all
    monkeypatch.setattr(cb, "_TREE_ROOT", tmp_path / "empty")
    absent = cb.discover("celldiag")
    assert absent.status == "no-tree" and not absent.ok

    # (b) a tree that exists, IS configured, and was never built.
    #     The generated Makefiles are load-bearing in this fixture: without
    #     them the tree is *unconfigured*, a third, distinct status, and the
    #     fixture would model "unconfigured" while asserting "unbuilt".
    clone = tmp_path / "tree"
    (clone / "capture_cell_diag").mkdir(parents=True)
    (clone / "Makefile").write_text("# generated by ./configure\n")
    (clone / "capture_cell_diag" / "Makefile").write_text("# generated\n")
    monkeypatch.setattr(cb, "_TREE_ROOT", clone)
    unbuilt = cb.discover("celldiag")
    assert unbuilt.status == "not-built" and not unbuilt.ok

    assert absent.status != unbuilt.status
    assert absent.skip_reason() != unbuilt.skip_reason()
    # The actionable one carries the command that fixes it.
    assert "make -C" in unbuilt.skip_reason()
    assert "make -C" not in absent.skip_reason()


def test_a_present_built_driver_is_found_with_no_env(tmp_path, monkeypatch):
    """Property 1, tested against a fabricated tree so it holds everywhere."""
    for env_var, _, _ in cb.ROLES.values():
        monkeypatch.delenv(env_var, raising=False)
    clone = tmp_path / "tree"
    rel = cb.ROLES["logstream"][1]
    exe = clone / rel
    exe.parent.mkdir(parents=True, exist_ok=True)
    exe.write_text("#!/bin/sh\nexit 0\n")
    exe.chmod(0o755)
    monkeypatch.setattr(cb, "_TREE_ROOT", clone)

    found = cb.discover("logstream")
    assert found.status == "discovered" and found.path == exe


def test_an_explicit_env_var_still_wins(tmp_path, monkeypatch):
    """Discovery is a fallback, not an override: an operator pointing at a
    binary outside this tree must keep getting that binary."""
    exe = tmp_path / "elsewhere"
    exe.write_text("#!/bin/sh\nexit 0\n")
    exe.chmod(0o755)
    monkeypatch.setenv("KP_CELLDIAG_BIN", str(exe))
    found = cb.discover("celldiag")
    assert found.status == "env" and found.path == exe


def test_a_bad_env_var_is_reported_not_silently_replaced(tmp_path, monkeypatch):
    """If the operator set the variable and it is wrong, say so -- falling
    through to discovery would run a DIFFERENT binary than the one asked for and
    report agreement about it."""
    monkeypatch.setenv("KP_CELLDIAG_BIN", str(tmp_path / "nope"))
    found = cb.discover("celldiag")
    assert found.status == "env-bad" and not found.ok


