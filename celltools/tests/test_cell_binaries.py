def _unconfigured_clone(tmp_path, monkeypatch=None):
    """A tree as it comes off `git clone`: Makefile.in, no Makefile."""
    clone = tmp_path / "tree"
    (clone / "capture_cell_diag").mkdir(parents=True)
    (clone / "Makefile.in").write_text("# autotools template\n")
    (clone / "capture_cell_diag" / "Makefile.in").write_text("# template\n")
    if monkeypatch is not None:
        monkeypatch.setattr(cb, "_TREE_ROOT", clone)
    return clone


def test_an_unconfigured_clone_is_not_reported_as_build_failed(tmp_path, monkeypatch):
    """`build-failed` means "a real breakage -- investigate".

    An unconfigured tree is not a breakage, it is a fact about the host, and
    make's *"No rule to make target"* says nothing about the target name. The
    status must name the actual condition and carry the actual remedy.
    """
    for env_var, _, _ in cb.ROLES.values():
        monkeypatch.delenv(env_var, raising=False)
    _unconfigured_clone(tmp_path, monkeypatch)
    # Pin the configure-dep probe: on a host MISSING a configure-time dep the
    # correct status is `not-configurable`, so without this the test's answer
    # depends on which machine runs it.
    monkeypatch.setattr(cb, "missing_configure_deps", lambda clone: [])

    found = cb.discover("celldiag", allow_build=True)
    assert found.status == "not-configured", \
        f"unconfigured tree reported as {found.status!r}"
    assert not found.ok
    assert "./configure" in found.skip_reason()


def test_an_unconfigured_clone_stays_not_configured_even_under_build(tmp_path, monkeypatch):
    """Opting into --build must not turn this into `build-failed`.

    The check precedes the build branch precisely so that `make` is never
    invoked in a tree where it cannot work; otherwise the accurate status is
    destroyed by the very attempt that was doomed by it.
    """
    for env_var, _, _ in cb.ROLES.values():
        monkeypatch.delenv(env_var, raising=False)
    _unconfigured_clone(tmp_path, monkeypatch)
    monkeypatch.setenv("KP_CELL_BUILD", "1")
    monkeypatch.setattr(cb, "missing_configure_deps", lambda clone: [])

    called = []
    monkeypatch.setattr(cb, "_build",
                        lambda *a, **k: called.append(a) or (False, "boom"))

    found = cb.discover("celldiag")
    assert found.status == "not-configured"
    assert called == [], "make was invoked on a tree with no makefile"


def test_three_skip_reasons_are_mutually_distinguishable(tmp_path, monkeypatch):
    """no-tree / not-configured / not-built must be three different strings."""
    for env_var, _, _ in cb.ROLES.values():
        monkeypatch.delenv(env_var, raising=False)
    monkeypatch.delenv("KP_CELL_BUILD", raising=False)

    monkeypatch.setattr(cb, "_TREE_ROOT", tmp_path / "empty")
    absent = cb.discover("celldiag")

    clone = _unconfigured_clone(tmp_path, monkeypatch)
    monkeypatch.setattr(cb, "missing_configure_deps", lambda clone: [])
    unconfigured = cb.discover("celldiag")

    (clone / "Makefile").write_text("# generated\n")
    (clone / "capture_cell_diag" / "Makefile").write_text("# generated\n")
    unbuilt = cb.discover("celldiag")

    statuses = {absent.status, unconfigured.status, unbuilt.status}
    assert statuses == {"no-tree", "not-configured", "not-built"}
    reasons = {absent.skip_reason(), unconfigured.skip_reason(), unbuilt.skip_reason()}
    assert len(reasons) == 3

    # Each actionable one carries ITS OWN remedy, not the other's.
    assert "./configure" in unconfigured.skip_reason()
    assert "./configure" not in unbuilt.skip_reason()
    assert "make -C" in unbuilt.skip_reason()


# ── A tree that CANNOT be configured is a host fact, not an omission ──
#
# On a host without libwebsockets, `./configure` hard-fails:
#
#     checking for libwebsockets >= 3.1.0... no
#     configure: error: Package requirements (libwebsockets >= 3.1.0) were not met
#
# The capture binaries do not use libwebsockets themselves; their autoconf build
# is gated on a Kismet SERVER dependency only because that build path is the
# top-level autoconf configure. Telling the operator to run `./configure`
# there is a remedy that cannot work, i.e. a skip whose stated cause is wrong.

def test_a_tree_that_cannot_be_configured_is_its_own_status(tmp_path, monkeypatch):
    """`not-configured` (an omission) vs `not-configurable` (a host fact)."""
    for env_var, _, _ in cb.ROLES.values():
        monkeypatch.delenv(env_var, raising=False)
    monkeypatch.delenv("KP_CELL_BUILD", raising=False)
    _unconfigured_clone(tmp_path, monkeypatch)
    monkeypatch.setattr(cb, "missing_configure_deps",
                        lambda clone: ["libwebsockets"])

    found = cb.discover("celldiag", allow_build=True)
    assert found.status == "not-configurable", \
        f"a host missing a configure dep reported as {found.status!r}"
    assert not found.ok


def test_the_unconfigurable_remedy_names_the_package_not_configure(tmp_path,
                                                                   monkeypatch):
    """The remedy must NOT be `./configure`.

    Advising a command that hard-fails is worse than advising nothing: it reads
    as "you forgot a step" when the truth is "this machine cannot do it", and
    the operator burns a cycle discovering that."""
    for env_var, _, _ in cb.ROLES.values():
        monkeypatch.delenv(env_var, raising=False)
    _unconfigured_clone(tmp_path, monkeypatch)
    monkeypatch.setattr(cb, "missing_configure_deps",
                        lambda clone: ["libwebsockets"])

    reason = cb.discover("celldiag").skip_reason()
    assert "libwebsockets" in reason, "the missing module is not named"
    assert "libwebsockets-dev" in reason, "no installable package named"
    assert "run `cd" not in reason and "./configure`, then" not in reason, \
        f"the unconfigurable remedy still tells the operator to ./configure: {reason}"


def test_every_role_records_whether_it_has_a_standalone_build(tmp_path,
                                                              monkeypatch):
    """The two tables must PARTITION ``ROLES``.

    A role in neither leaves role-generic code reaching for a fact it does not
    have, and filling the gap with prose written about some other role. ``_standalone_note`` degrades to an explicit
    "unrecorded" rather than a wrong sentence, and this asserts we never ship
    that."""
    assert not (set(cb._STANDALONE_ESCAPE) &
                set(cb._NO_STANDALONE_ESCAPE)), \
        "a role cannot both have and not have a standalone build"
    assert set(cb._STANDALONE_ESCAPE) | set(cb._NO_STANDALONE_ESCAPE) \
        == set(cb.ROLES), "a role's standalone status is unrecorded"
    for role in cb.ROLES:
        assert "unrecorded" not in cb._standalone_note(role, tmp_path)


def test_the_standalone_advice_names_a_makefile_that_actually_exists():
    """The escape hatch must not point at a missing file.

    The standalone build is the one documented escape from a
    `not-configurable` host, so advice naming a ``standalone.mk`` that does not
    exist is a dead end that reads exactly like advice that works. Every
    ``-C <dir> -f standalone.mk`` this module can print is checked against the
    real tree."""
    clone = cb.tree_root()
    if clone is None:
        pytest.skip("KP_ROOT does not point at a source tree")
    advised = set()
    for role in cb.ROLES:
        for m in re.finditer(r"-C (\S+) -f standalone\.mk",
                             cb._standalone_note(role, clone)):
            advised.add(Path(m.group(1)))
    assert advised, "no role advises a standalone build at all"
    for d in sorted(advised):
        assert (d / "standalone.mk").is_file(), \
            f"advised `make -C {d} -f standalone.mk` but {d}/standalone.mk is absent"


@pytest.mark.parametrize("role", sorted(cb.ROLES))
def test_the_standalone_advice_never_names_another_roles_binary(role):
    """The copy-paste tell, pinned per role.

    A note that names one role's binary while advising a build in another
    role's directory and offering a third role's override variable cannot be
    acted on. A reader must be able to use this text without first checking
    which driver it was written about, so no role's note may name another
    role's binary as the thing to build."""
    note = cb._standalone_note(role, cb.tree_root() or Path("/CLONE"))
    mine = Path(cb.ROLES[role][1]).name
    for other, (_, rel, _) in cb.ROLES.items():
        binary = Path(rel).name
        if other == role or binary == mine:
            continue
        assert f"build it{binary}" not in note, note
        # The `logstream` escape is deliberately cross-referenced from the roles
        # that have none -- as a NAMED OTHER role, never as this role's remedy.
        if binary in note:
            assert f"`{other}` role" in note or f"{other}-dump" in note, \
                f"{role}'s note names {binary} without saying whose it is: {note}"


def test_the_cellat_standalone_makefile_covers_every_lws_free_binary():
    """A selftest added to Makefile.in and not to standalone.mk goes MISSING.

    ``standalone.mk`` is a hand-maintained mirror of the framework-free recipes
    in ``Makefile.in`` -- it cannot include them, because Makefile.in's first
    line is ``include ../Makefile.inc``, itself generated by configure. That
    makes drift the obvious failure mode, and drift here is silent: the
    unconfigurable host simply never runs the new check. So the mirror is
    asserted rather than trusted.

    ``make check``'s prerequisite list in Makefile.in is the source of truth for
    "framework-free selftest", since anything needing the framework could not be
    a bare ``$(CC)`` recipe there either."""
    clone = cb.tree_root()
    if clone is None:
        pytest.skip("KP_ROOT does not point at a source tree")
    d = clone / "capture_cell_at"
    template = (d / "Makefile.in").read_text()
    standalone = (d / "standalone.mk").read_text()

    binvars = dict(re.findall(r"^(\w+_BIN)\s*=\s*(\S+)\s*$", template, re.M))
    check = re.search(r"^check:((?:.*\\\n)*.*)$", template, re.M).group(1)
    expected = {binvars[v] for v in re.findall(r"\$\((\w+_BIN)\)", check)}
    assert expected, "could not resolve Makefile.in's `check` prerequisites"

    covered = set(re.findall(r"^\t(test_\w+)", standalone, re.M)) | \
        set(re.split(r"\s+", re.search(r"^TESTS\s*=\s*((?:.*\\\n)*.*)$",
                                       standalone, re.M).group(1)
                     .replace("\\\n", " ").strip()))
    missing = expected - covered
    assert not missing, \
        (f"capture_cell_at/standalone.mk does not build {sorted(missing)}, "
         f"which `make check` runs -- an unconfigurable host silently skips them")


def test_the_cellat_standalone_makefile_lists_and_defines_each_selftest_once():
    """A mirror fix applied twice is also drift.

    A selftest listed twice in ``TESTS`` with its recipe defined twice makes
    make only warn ("overriding recipe"), ``check`` then runs the test twice,
    and the coverage test above stays green, so duplicates are asserted here."""
    clone = cb.tree_root()
    if clone is None:
        pytest.skip("KP_ROOT does not point at a source tree")
    standalone = (clone / "capture_cell_at" / "standalone.mk").read_text()

    tests = re.split(r"\s+", re.search(r"^TESTS\s*=\s*((?:.*\\\n)*.*)$",
                                       standalone, re.M).group(1)
                     .replace("\\\n", " ").strip())
    listed_twice = sorted({t for t in tests if tests.count(t) > 1})
    assert not listed_twice, f"standalone.mk TESTS lists {listed_twice} more than once"

    targets = re.findall(r"^([\w$()]+):(?!=)", standalone, re.M)
    defined_twice = sorted({t for t in targets if targets.count(t) > 1})
    assert not defined_twice, f"standalone.mk defines {defined_twice} more than once"


def _header_root(tmp_path, *, present: bool):
    """A synthetic ``_HEADER_ROOTS`` entry, with or without the probed header.

    The tests below must control this. ``_HEADER_ROOTS`` is three ABSOLUTE
    system paths (``/usr/include``, ...), so ``tmp_path`` does not isolate the
    header probe -- ``tmp_path`` isolates the ``clone`` argument, which that
    probe never reads. Left uncontrolled, these assertions would depend on
    whether the developer's host has ``libsensors-dev`` installed.
    """
    root = tmp_path / ("with-headers" if present else "without-headers")
    for header in cb._CONFIGURE_HEADER_DEPS:
        path = root / header
        if present:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text("/* synthetic */\n")
    root.mkdir(parents=True, exist_ok=True)
    return root


def test_the_dep_probe_does_not_guess_when_pkg_config_is_absent(tmp_path,
                                                                monkeypatch):
    """No pkg-config -> we cannot tell about the PKG-CONFIG deps, so name none.

    Returning "everything is missing" would substitute one wrong cause for
    another, which is the failure this whole status family exists to avoid.

    The contract is "we do not guess about the half we cannot measure", NOT
    "we return nothing" -- the header probe is answerable without pkg-config and
    still reports (next test). The headers are forced PRESENT here so this
    assertion is about the pkg-config half alone and holds on every host."""
    monkeypatch.setattr(cb, "_HEADER_ROOTS",
                        (str(_header_root(tmp_path, present=True)),))
    monkeypatch.setattr(cb.shutil, "which", lambda name: None)
    assert cb.missing_configure_deps(tmp_path) == []


def test_a_missing_header_is_still_reported_when_pkg_config_is_absent(
        tmp_path, monkeypatch):
    """The other half of the same contract.

    ``missing_configure_deps`` runs two probes and only one goes through
    ``which``. The header probe stands alone deliberately: a missing header is
    a fact we CAN establish on a host with no pkg-config, and a skip must
    not print a remedy that hard-fails. Suppressing it to make the sibling test's ``== []``
    true would trade a measurable cause for an invented one."""
    monkeypatch.setattr(cb, "_HEADER_ROOTS",
                        (str(_header_root(tmp_path, present=False)),))
    monkeypatch.setattr(cb.shutil, "which", lambda name: None)
    assert cb.missing_configure_deps(tmp_path) == \
        sorted(cb._CONFIGURE_HEADER_DEPS)


def test_every_named_header_dep_carries_an_installable_remedy(tmp_path,
                                                              monkeypatch):
    """A dep must never be named without a remedy.

    ``_dep_remedy`` indexes ``_CONFIGURE_HEADER_DEPS`` with ``[]`` after a
    ``.get`` miss on the pkg table, so a header added to the probe list without
    a remedy raises ``KeyError`` from inside ``discover()`` rather than printing a
    hint. Pinned here so the failure surfaces as a test, not as a traceback on
    an operator's terminal."""
    monkeypatch.setattr(cb, "_HEADER_ROOTS",
                        (str(_header_root(tmp_path, present=False)),))
    monkeypatch.setattr(cb.shutil, "which", lambda name: None)
    for dep in cb.missing_configure_deps(tmp_path):
        assert cb._dep_remedy(dep).strip(), f"{dep} names no remedy"


def test_the_named_deps_are_not_used_by_the_drivers_under_test():
    """The finding itself, pinned so it cannot quietly stop being true.

    If capture_cell_diag ever DOES take a libwebsockets dependency, the
    argument that "the autoconf build is gated on an irrelevant dep" changes, and this
    fails rather than the docs going quietly stale.

    This test measures the directory, not the link closure. The link closure
    is ``test_the_capture_framework_keeps_every_lws_reference_behind_its_ifdef``
    below. Kept because the narrow fact is still worth a trip-wire -- the
    drivers' own sources really do not use lws -- but it must not be read
    alone."""
    clone = cb.tree_root()
    if clone is None:
        pytest.skip("KP_ROOT does not point at a source tree")
    src = clone / "capture_cell_diag"
    hits = []
    for f in list(src.glob("*.c")) + list(src.glob("*.cpp")) + list(src.glob("*.h")):
        text = f.read_text(errors="replace")
        if "libwebsockets" in text or "lws_" in text:
            hits.append(f.name)
    assert not hits, (
        f"capture_cell_diag now references libwebsockets ({hits}) -- the "
        "premise was that the capture binaries use none of the configure-time "
        "deps that gate the autoconf build. Re-check _CONFIGURE_PKG_DEPS.")


def _lws_unguarded_lines(text: str) -> list[tuple[int, str]]:
    """Lines naming libwebsockets that sit OUTSIDE an ``#ifdef HAVE_LIBWEBSOCKETS``.

    Tracks the preprocessor stack: an ``#ifdef``/``#if`` on the macro opens a
    positive frame, ``#ifndef``/``#if !`` a negative one, ``#else`` flips it. A
    line is guarded when any enclosing frame is positive.
    """
    stack: list[int] = []
    bad = []
    for n, line in enumerate(text.splitlines(), 1):
        s = line.strip()
        m = re.match(r"#\s*(ifdef|ifndef|if|elif|else|endif)\b(.*)", s)
        if m:
            kw, rest = m.group(1), m.group(2)
            lws = "HAVE_LIBWEBSOCKETS" in rest
            if kw == "ifdef":
                stack.append(1 if lws else 0)
            elif kw == "ifndef":
                stack.append(-1 if lws else 0)
            elif kw == "if":
                stack.append((-1 if "!" in rest else 1) if lws else 0)
            elif kw == "elif" and stack:
                stack[-1] = 0
            elif kw == "else" and stack:
                stack[-1] = -stack[-1]
            elif kw == "endif" and stack:
                stack.pop()
            continue
        if ("lws_" in line or "libwebsockets.h" in line) and 1 not in stack:
            bad.append((n, s))
    return bad


def test_the_lws_scanner_flags_an_unguarded_reference():
    """Positive control for the invariant below: a scanner that never reads
    positive cannot be read as negative."""
    assert _lws_unguarded_lines(
        "#include <libwebsockets.h>\nstruct x { struct lws_context *c; };\n")
    assert _lws_unguarded_lines(
        "#ifndef HAVE_LIBWEBSOCKETS\nstruct lws_ring *r;\n#endif\n")
    assert _lws_unguarded_lines(
        "#ifdef HAVE_LIBWEBSOCKETS\n#else\nstruct lws_vhost *v;\n#endif\n")
    assert not _lws_unguarded_lines(
        "#ifdef HAVE_LIBWEBSOCKETS\n#include <libwebsockets.h>\n"
        "#ifdef SYS_LINUX\nstruct lws_context *c;\n#endif\n#endif\n")


def test_the_capture_framework_keeps_every_lws_reference_behind_its_ifdef():
    """The capture framework's libwebsockets use stays behind its ``#ifdef``.

    What matters is the LINK CLOSURE, not the driver directory:
    ``kismet_cap_cell_*`` link capture_framework. Every lws include, every
    ``struct lws_*`` member and every lws call site there is under
    ``#ifdef HAVE_LIBWEBSOCKETS``, so with the macro undefined both capture
    drivers link against libc alone (Darwin: libSystem only). The dependency is
    a configure choice, and the standalone builds make it optional.

    That holds only while no lws reference sits outside the guard. One
    unguarded ``lws_`` line breaks every no-lws build, including Darwin, while
    every Linux host that has lws stays green.
    """
    clone = cb.tree_root()
    if clone is None:
        pytest.skip("KP_ROOT does not point at a source tree")
    for name in ("capture_framework.h", "capture_framework.c"):
        f = clone / name
        if not f.exists():
            pytest.skip(f"this tree has no {name}")
        bad = _lws_unguarded_lines(f.read_text(errors="replace"))
        assert not bad, (
            f"{name} references libwebsockets outside #ifdef HAVE_LIBWEBSOCKETS "
            f"at {bad[:5]} -- the no-lws standalone builds (Linux without lws, "
            f"every Darwin host) can no longer compile")

    # The logstream driver must stay framework-free: it is the one leg that
    # needs no framework at all, and so the one runnable with only libc.
    dump_src = clone / "capture_cell_diag" / "diag_logstream.c"
    if dump_src.exists():
        body = dump_src.read_text(errors="replace")
        assert "capture_framework" not in body and "lws_" not in body, (
            "diag_logstream.c now pulls in the capture framework")


def test_a_standalone_build_path_exists_for_the_half_that_can_have_one():
    """A standalone build path exists for capture_cell_diag.

    Asserts the file takes NO autoconf input. ``Makefile.in`` exists in that
    directory and is NOT a standalone path -- it is rendered by the top-level
    ``config.status`` and its first line is ``include ../Makefile.inc``, itself
    generated by ``configure``. *"It already has a Makefile.in"* is exactly the
    reasoning this test exists to refuse.
    """
    clone = cb.tree_root()
    if clone is None:
        pytest.skip("KP_ROOT does not point at a source tree")
    mk = clone / "capture_cell_diag" / "standalone.mk"
    assert mk.exists(), "capture_cell_diag/standalone.mk is missing"

    body = mk.read_text(errors="replace")

    # Comment lines are stripped first. The file's own header EXPLAINS why
    # Makefile.in's `include ../Makefile.inc` disqualifies it, so a naive
    # substring search over the whole text matches the explanation and reports
    # the opposite of the truth. Assert on what make will execute.
    code = "\n".join(
        line for line in body.splitlines() if not line.lstrip().startswith("#")
    )
    assert "include ../Makefile.inc" not in code, (
        "standalone.mk includes the configure-generated Makefile.inc, so it is "
        "not standalone at all"
    )
    assert "@" + "CC@" not in code, "standalone.mk carries an autoconf substitution"

    # It must build the logstream dump and offer a check target, or it does
    # not reduce the "unverified here" surface.
    assert "diag_logstream_dump" in body
    assert "check:" in body

    # ...and it MUST build the helper, native decode linked in: that is the
    # binary that ships, and the one a host that cannot ./configure tests.
    assert "$(NATIVE_BIN):" in code, (
        "standalone.mk no longer builds the helper. It must stay buildable on a "
        "tree that has never run ./configure")
    assert re.search(r"^native:", code, re.M), \
        "standalone.mk lost its `native` target"
    assert re.search(r"^\.DEFAULT_GOAL\s*:=\s*check-native\b", code, re.M), \
        "standalone.mk's default goal is no longer check-native"


def test_the_standalone_helper_does_not_write_the_autoconf_output_path():
    """Two makefiles must not share one output path.

    If ``standalone.mk``'s ``NATIVE_BIN`` equals ``Makefile.in``'s
    ``MONITOR_BIN``, running the documented buildability check --

        make -C capture_cell_diag -f standalone.mk

    -- inside a CONFIGURED tree silently replaces the autoconf-built helper with
    a differently-built one (different ``config.h`` resolution, different ``-I``
    order, different link line), and every consumer afterwards measures the
    wrong artifact. Both builds exit 0 and both pass the symbol guard, so the
    symptom surfaces as unrelated-looking failures nowhere near the build
    system. This pins that standalone.mk keeps its output elsewhere.
    """
    clone = cb.tree_root()
    if clone is None:
        pytest.skip("KP_ROOT does not point at a source tree")

    d = clone / "capture_cell_diag"
    mk_in = d / "Makefile.in"
    mk_alone = d / "standalone.mk"
    if not (mk_in.exists() and mk_alone.exists()):
        pytest.skip("this tree has no capture_cell_diag build files")

    def _assign(text: str, var: str) -> str | None:
        """The single-line value of ``var = ...``, comments stripped."""
        for line in text.splitlines():
            if line.lstrip().startswith("#"):
                continue
            m = re.match(rf"{re.escape(var)}\s*[:?]?=\s*(.*)", line.strip())
            if m:
                return m.group(1).strip()
        return None

    monitor = _assign(mk_in.read_text(errors="replace"), "MONITOR_BIN")
    native = _assign(mk_alone.read_text(errors="replace"), "NATIVE_BIN")
    native_dir = _assign(mk_alone.read_text(errors="replace"), "NATIVE_DIR")

    assert monitor, "could not parse MONITOR_BIN out of Makefile.in"
    assert native, "could not parse NATIVE_BIN out of standalone.mk"
    assert native_dir, "could not parse NATIVE_DIR out of standalone.mk"

    assert native != monitor, (
        f"standalone.mk writes {native!r}, the SAME path Makefile.in's "
        f"MONITOR_BIN writes. In a configured tree the buildability check then "
        f"clobbers the deliverable, and no guard downstream can tell."
    )

    # ...and specifically it must land under the directory standalone.mk owns
    # outright -- anywhere else is a new shared path rather than a fixed one.
    assert native.startswith("$(NATIVE_DIR)/"), (
        f"NATIVE_BIN is {native!r}; it must live under $(NATIVE_DIR) "
        f"({native_dir!r}), which standalone.mk owns and .gitignore covers"
    )
    # Discovery and the staleness guard look for it there.
    assert cb._STANDALONE_ESCAPE["celldiag"][2] == \
        f"{native_dir}/{Path(cb.ROLES['celldiag'][1]).name}"


def test_standalone_module_set_matches_the_autoconf_one():
    """The two module lists are a hand-maintained MIRROR, and mirrors drift.

    ``standalone.mk``'s ``BASELINE_CELLDIAG_SRCS`` and ``Makefile.in``'s
    ``MONITOR_OBJS`` name the same pure-C module set in two files. Nothing makes
    them agree, and a divergence is silent in the worst direction: the
    standalone helper builds, links, and passes its symbol guard while missing
    a module the autoconf build has.

    Both files already pin their own COUNT at link time. A count catches a drop;
    it does not catch a swap. This diffs the names.
    """
    clone = cb.tree_root()
    if clone is None:
        pytest.skip("KP_ROOT does not point at a source tree")

    d = clone / "capture_cell_diag"
    mk_in = d / "Makefile.in"
    mk_alone = d / "standalone.mk"
    if not (mk_in.exists() and mk_alone.exists()):
        pytest.skip("this tree has no capture_cell_diag build files")

    def _block(text: str, var: str) -> set[str]:
        """The whitespace/backslash-continued value of `var = ...`."""
        out: list[str] = []
        collecting = False
        for line in text.splitlines():
            stripped = line.strip()
            if not collecting:
                if stripped.startswith(f"{var} ="):
                    collecting = True
                    stripped = stripped.split("=", 1)[1].strip()
                else:
                    continue
            more = stripped.endswith("\\")
            out.extend(stripped.rstrip("\\").split())
            if not more:
                break
        return {t for t in out if t.endswith((".c", ".c.o"))}

    autoconf = {n[: -len(".o")] if n.endswith(".c.o") else n
                for n in _block(mk_in.read_text(errors="replace"), "MONITOR_OBJS")}
    standalone = _block(mk_alone.read_text(errors="replace"), "BASELINE_CELLDIAG_SRCS")

    assert autoconf, "could not parse MONITOR_OBJS out of Makefile.in"
    assert standalone, "could not parse BASELINE_CELLDIAG_SRCS out of standalone.mk"
    assert autoconf == standalone, (
        "the standalone helper and the autoconf helper disagree on the "
        f"pure-C module set.\n"
        f"  only in Makefile.in:   {sorted(autoconf - standalone)}\n"
        f"  only in standalone.mk: {sorted(standalone - autoconf)}"
    )

# ── The capture binaries' no-configure builds ────────────────────────────────
# Both capture binaries build on Linux and Darwin via standalone.mk, into a
# build directory of their own (never the autoconf output path): `native` ->
# build-native/ for the DIAG helper, `baseline` -> build-baseline/ for the AT
# one. Discovery, the build path, and the staleness guard each have to know
# where that is.


def _exe(path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("#!/bin/sh\n")
    path.chmod(0o755)
    return path


def _clear_role_env(monkeypatch):
    for env_var, _, _ in cb.ROLES.values():
        monkeypatch.delenv(env_var, raising=False)
    monkeypatch.delenv("KP_CELL_BUILD", raising=False)


@pytest.mark.parametrize("role", ["celldiag", "cellat"])
def test_a_standalone_build_is_discovered_on_an_unconfigured_tree(
        role, tmp_path, monkeypatch):
    """Discovery must look beyond the autoconf output path, or a standalone
    build made by hand is invisible and the role still skips."""
    _clear_role_env(monkeypatch)
    clone = _unconfigured_clone(tmp_path, monkeypatch)
    subdir, _target, out = cb._STANDALONE_ESCAPE[role]
    built = _exe(clone / subdir / out)

    found = cb.discover(role)
    assert found.status == "discovered", found
    assert found.path == built
    assert "standalone.mk" in found.detail


def test_the_autoconf_binary_wins_over_the_standalone_build(tmp_path,
                                                               monkeypatch):
    """On a configured tree the autoconf binary is what Linux users get; a side
    build must not silently become the thing measured."""
    _clear_role_env(monkeypatch)
    clone = _unconfigured_clone(tmp_path, monkeypatch)
    primary = _exe(clone / cb.ROLES["celldiag"][1])
    _exe(clone / "capture_cell_diag" / "build-native" / "kismet_cap_cell_diag")
