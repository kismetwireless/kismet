@pytest.mark.parametrize("preset", ["all", "high", "error"])
def test_f3_presets_are_armed_but_not_relayed(tmp_path, preset):
    """An ``f3=`` preset is ARMED, reported as ``<preset>+norelay``, announced
    once, adds no message traffic, and costs no cell observation.

    The option drives two different mechanisms. **F3 arming**
    (``SET_ALL_RT_MASKS`` sent to a modem) is live-only and works. **F3
    relay** -- decoding the F3 prints into ``diag_f3`` message lines -- is not
    something this source does: the prints stay in the byte stream, where a
    ``rawlog=`` tee or the raw DIAG packets keep them for an offline decoder.
    Reporting ``f3_preset`` as the bare preset name while relaying nothing
    would be a quiet lie, so every clause here guards one part of saying so.

    ``high`` and ``error`` are the subtractive severity floors (``high`` sends
    ``0xFFFFFFFC``, ``error`` ``0xFFFFFFF8``). The mask is enforced by the
    *modem*, so on a replay a floor changes nothing about the stream; what this
    pins offline is that the source carries a *distinct* preset rather than
    collapsing every armed state to "all". A floor reported as ``all`` would
    tell the web-UI panel's reader they armed the full trace while part of it
    is silenced at the modem.
    """
    binary = _binary_or_skip()
    replay = _fixture(tmp_path)

    default = CellDiagRun(binary, _definition(replay)).run()
    run = CellDiagRun(binary, _definition(replay, f3=preset, stats_interval=1),
                      timeout=60.0).run()
    assert run.open_code in (1, None) and not run.errors, (
        f"f3={preset}: code={run.open_code} errors={run.errors}")

    # Liveness-only objects (the decoder watchdog's) carry helper_alive and
    # decode_mode and nothing else, by design: no preset.
    stats = [s for s in _diag_stats_lines(run) if "bytes_read" in s]
    assert stats, "no diag_stats object relayed"
    assert all(s.get("f3_preset") == f"{preset}+norelay" for s in stats), (
        f"a source that does not relay F3 reported its preset as if it did, or "
        f"collapsed a floor into another preset — expected {preset!r}+norelay: "
        f"{stats}")
    # Against the `f3`-unset CONTROL, not against an empty set. The filter is a
    # denylist of the control lines this source emits on its own, which is not
    # enough to answer "is there nothing extra here" — the open message and the
    # per-fix GPS lines are neither F3 nor listed in it. The honest form of "no
    # F3 was relayed" is "the same message traffic as with F3 off".
    assert len(_f3_relay_messages(run)) == len(_f3_relay_messages(default)), (
        f"f3={preset} added message traffic: "
        f"{len(_f3_relay_messages(run))} vs {len(_f3_relay_messages(default))} "
        f"with F3 off")
    announced = [m for m in run.messages if "ARMED BUT NOT RELAYED" in m]
    assert len(announced) == 1, (
        f"the armed-but-unrelayed state must be announced exactly once: "
        f"{announced or run.messages[:10]}")
    # The remedy has to be one the operator can carry out: say where the F3
    # prints DO go.
    assert "rawlog=" in announced[0] and "rawpackets" in announced[0], (
        f"the announcement does not say where the F3 prints DO go: {announced[0]}")
    assert f"{preset}+norelay" in announced[0], (
        f"the announcement does not name the readout's spelling: {announced[0]}")
    assert _canon(run.observations) == _canon(default.observations), (
        f"f3={preset} changed the cell stream: {len(run.observations)} "
        f"observations vs {len(default.observations)} with F3 off. Arming a "
        f"debug log preset must not cost cell decode.")


