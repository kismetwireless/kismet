"""Offline harness for the Kismet ``kismet_cap_cell_diag`` capture binary.

Drives the compiled capture binary end-to-end **without a live modem or a running
Kismet server** by speaking just enough of the Kismet ``kismet_external`` **v3**
datasource protocol (msgpack over ``--in-fd``/``--out-fd``) to:

* send an ``OPENREQ`` with a ``celldiag-<imei>:replay=<file>`` source definition,
* read back the ``PACKET`` (DATAREPORT) frames the binary relays, and
* extract the ``cell_observation`` JSON each carries.

The binary decodes in process, with its native legs, and starts no other
program. What this file pins is everything around that decode: the option
surface (``mask=``, ``f3=``, ``enabled=``, ``rawlog=``, ``gsmtap=``, the
refused decode options), the runtime ``set_channel`` knobs, the census and
``diag_stats`` control lines, the decoder's liveness readout, and the proof that
the source runs nothing but itself.

Every test here replays bytes that ship in this tree: the synthesised
functional fixture (``functional.hdlc``, in capture_cell_diag's fixtures; four
``0xB193`` records, see its generator) or streams built from it. Tests that need real modem captures
live in a separate directory and do not ship.

The module skips cleanly when no built ``kismet_cap_cell_diag`` is found, and
FAILS when the one it finds is older than its sources.

The run harness -- ``CellDiagRun``, binary discovery and the staleness guard,
``_definition``, ``_diag_stats_lines`` -- is shared with the other celldiag
tests and lives in ``celldiag_run``; the v3 protocol layer under it is
``kismet_capture_ipc``. What remains here is the fixtures and the tests.
"""

