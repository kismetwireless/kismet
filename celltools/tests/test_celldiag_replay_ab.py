def test_the_decoder_readout_accounts_for_every_record(tmp_path):
    """The decoder's readout reports real coverage, and its arithmetic closes.

    The readout is a message-bus line of the form::

        <src> nativedecode=only | records=N native=M (P%) obs=K declined=D
              enriched=E | ... | no-leg=L | frames=F crc_bad=C wrapped=W |
              emitted=X ...

    Every recovered LOG record either reaches a leg (``native``) or has none
    (``no-leg``), so the two must sum to ``records``: a gap means records lost
    between extraction and routing. ``emitted`` is what the decoder sent, so it
    must equal what the server actually received. Asserting on the parsed
    counters rather than the string keeps this pinned to the routing behaviour,
    not to the format.
    """
    binary = _binary_or_skip()
    replay = _fixture(tmp_path)

    run = CellDiagRun(binary, _definition(replay)).run()
    assert not run.errors, f"run reported errors: {run.errors}"

    lines = [m for m in run.messages if "nativedecode=only |" in m]
    assert lines, f"no decoder readout on the message bus; messages={run.messages}"

    final = lines[-1]      # the teardown line: post-flush totals
    records = _kv_int(final, "records")
    native = _kv_int(final, "native")
    obs = _kv_int(final, "obs")
    no_leg = _kv_int(final, "no-leg")
    emitted = _kv_int(final, "emitted")

    assert records > 0, f"the decoder saw no LOG records at all: {final!r}"
    assert native > 0, (
        f"{records} records recovered but NONE routed to a leg -- the legs are "
        f"linked but never reached: {final!r}")
    assert obs > 0, (
        f"legs ran on {native} records but produced 0 observations: {final!r}")
    assert native + no_leg == records, (
        f"routing does not account for every record ({native} + {no_leg} != "
        f"{records}): {final!r}")
    assert emitted == len(run.observations), (
        f"the decoder says it emitted {emitted} observations, the server "
        f"received {len(run.observations)}: {final!r}")


