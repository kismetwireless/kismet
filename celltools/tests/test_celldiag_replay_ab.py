# ── a stalled server must not stop the DIAG reader ───────────────────────────
# The reader thread sends each rendered observation into Kismet's output ring.
# If it WAITS when the ring is full, a server that stops draining stops this
# source reading its port, and a live modem overruns: its bytes are lost to
# decoding, rawlog= and the raw stream alike. The contract is the raw-packet
# path's: a live source drops the record (counted, announced) and keeps
# reading.
#
# Live, not replay: a replay may wait (it is lossless by contract). The port
# is a pty fed non-blocking, so every byte the reader fails to take is a
# refused write -- a modem overrun. The server stall stays under the 15 s
# keepalive the capture requires. The overrun is compared as a RATIO against
# the same run's unstalled phase, because pty buffering differs by host.
_STALL_COPIES = 200                  # ~436 KB, ~1,800 obs/MB
_STALL_RATE_BPS = 1_000_000
_STALL_WARM_S, _STALL_S, _STALL_AFTER_S = 5.0, 12.0, 6.0
_FUTEX_SYSCALL = "202"        # x86_64; the wait the fix removes parks here


class _StalledServerRun(CellDiagRun):
    """A server that stops reading its source for `_STALL_S` once `stall` is set."""
    stall = False
    stall_until = None

    @property
    def drain_pause_s(self):
        # The pump reads this twice per batch (the > 0 test, then the sleep),
        # so it is a deadline, not a one-shot.
        now = time.monotonic()
        if self.stall and self.stall_until is None:
            self.stall_until = now + _STALL_S
        if self.stall_until is not None and now < self.stall_until:
            return self.stall_until - now
        return 0.0

    @drain_pause_s.setter
    def drain_pause_s(self, _value):
        pass


def _task_syscalls(pid: int) -> dict[int, str]:
    out = {}
    for t in Path(f"/proc/{pid}/task").iterdir():
        try:
            out[int(t.name)] = (t / "syscall").read_text().split()[0]
        except (OSError, IndexError):
            pass
    return out


@pytest.mark.skipif(not sys.platform.startswith("linux") or os.uname().machine != "x86_64",
                    reason="reads /proc/<tid>/syscall with x86_64 syscall numbers")
def test_a_stalled_server_does_not_stop_the_live_diag_reader(tmp_path):
    import fcntl
    import tty
    from fake_at_modem import FakeAtModem

    binary = _binary_or_skip()
    data = _tiled_fixture(_STALL_COPIES)

    master, slave = os.openpty()
    tty.setraw(slave)
    fcntl.fcntl(master, fcntl.F_SETFL, fcntl.fcntl(master, fcntl.F_GETFL) | os.O_NONBLOCK)
    feed = {"accepted": 0, "refused": 0}
    stop = threading.Event()

    def feeder():
        off, sent, t0 = 0, 0, time.monotonic()
        while not stop.is_set():
            if sent >= (time.monotonic() - t0) * _STALL_RATE_BPS:
                time.sleep(0.002)
                continue
            piece = data[off:off + 16384] or data[:16384]
            off = (off + 16384) % len(data)
            sent += len(piece)
            try:
                n = os.write(master, piece)
                feed["accepted"] += n
                feed["refused"] += len(piece) - n
            except BlockingIOError:
                feed["refused"] += len(piece)
            except OSError:
                break

    phases = {"warm": [0, 0], "stall": [0, 0]}
    parked = {"longest_s": 0.0, "run_s": 0.0}
    state = {"close": False}

    def watch(run):
        pid = sigchld_probe.own_child(binary, time.monotonic() + 15)
        if pid is None:
            return
        t0, last = time.monotonic(), dict(feed)
        while time.monotonic() - t0 < _STALL_WARM_S + _STALL_S + _STALL_AFTER_S:
            time.sleep(0.5)
            t = time.monotonic() - t0
            try:
                sc = _task_syscalls(pid)
            except OSError:
                break
            acc = feed["accepted"] - last["accepted"]
            ref = feed["refused"] - last["refused"]
            last = dict(feed)
            if 1.0 <= t < _STALL_WARM_S:
                phases["warm"][0] += acc
                phases["warm"][1] += ref
            if t >= _STALL_WARM_S and not run.stall:
                run.stall = True
            # The ring needs a few seconds to fill; judge the back of the stall.
            if _STALL_WARM_S + 5.0 <= t < _STALL_WARM_S + _STALL_S:
                phases["stall"][0] += acc
                phases["stall"][1] += ref
            if _FUTEX_SYSCALL in sc.values():
                parked["run_s"] += 0.5
                parked["longest_s"] = max(parked["longest_s"], parked["run_s"])
            else:
                parked["run_s"] = 0.0
        state["close"] = True

    with FakeAtModem(imei=IMEI, firmware="STALLGATE") as at:
        definition = (f"celldiag-{IMEI}:atport={at.port},diagport={os.ttyname(slave)},"
                      f"nomask=true,defer=false,stats_interval=1")
        threading.Thread(target=feeder, daemon=True).start()
        run = _StalledServerRun(binary, definition,
                                timeout=_STALL_WARM_S + _STALL_S + _STALL_AFTER_S + 30,
                                close_when=lambda r: state["close"],
                                graceful_close_s=15.0, poll_s=0.05)
        w = threading.Thread(target=watch, args=(run,), daemon=True)
        w.start()
        run.run()
        stop.set()
        w.join(timeout=5)
    os.close(master)
    os.close(slave)

    stats = [json.loads(c) for c in run.control if '"diag_stats"' in c]
    dropped = max((s.get("obs_ring_dropped", 0) for s in stats), default=0)

    def ratio(acc_ref):
        acc, ref = acc_ref
        return ref / max(1, acc + ref)
    warm, stalled = ratio(phases["warm"]), ratio(phases["stall"])
    # All judged, then reported together: a binary that stalls fails on the
    # stall itself, not only on the first condition it happens to miss.
    problems = []
    if parked["longest_s"] >= 1.0:
        problems.append(
            f"a thread of the source sat in futex (the unbounded ring wait) for "
            f"{parked['longest_s']:.1f} s while the server stalled: the DIAG "
            f"reader stopped reading")
    if stalled > warm * 1.5 + 0.05:
        problems.append(
            f"the modem overran while the server stalled: {stalled:.0%} of its "
            f"bytes refused vs {warm:.0%} unstalled (accepted/refused bytes: "
            f"{phases['warm']} unstalled, {phases['stall']} stalled)")
    # The control: the stall must actually have filled the ring, or nothing
    # above was exercised.
    if dropped <= 0:
        problems.append(
            f"no ring-full drop was counted (obs_ring_dropped={dropped}): either "
            f"the stall never filled the ring, or the source waited instead of "
            f"dropping")
    elif not any("DROPPING" in m for m in run.messages):
        problems.append("the first ring-full drop was not announced on the bus")
    assert not problems, "\n".join(problems)


# ── helper_alive means "the decoder is alive" ────────────────────────────────
# There is no helper process; helper_alive keeps its wire name and reports the
# in-process decoder, judged from the DIAG reader's heartbeat by a watchdog
# thread. The upstream datasources panel renders a 0 as "DEAD -- observations
# have stopped", so the field must:
#
# * read 1, with a FLOWING verdict and `decoder=alive`, while records flow;
# * stay 1 on a quiet port: a silent modem is not a stuck decoder;
# * fall to 0 within the bound when the reader really stalls, with a loud
#   DECODER-STALLED verdict, and come back when the reader moves again --
#   the negative control that proves the 1 is not hard-coded.
#
# The stall is real, not simulated. rawlog= points at a FIFO whose reader
# never reads, so the capture thread blocks inside its tee write(), the same
# place a hung disk would block it. No test knob is compiled into the binary.

#: DIAG_STATS_DECODER_STALL_SEC and the watchdog's LIVE_TICK_NS.
_LIVE_BOUND_S = 10.0
_LIVE_TICK_S = 0.5
_STATS_PREFIX = "celldiag stats:"


class _TimedRun(CellDiagRun):
    """A run that also records WHEN each message and control object arrived."""

    def __init__(self, *a, **kw):
        super().__init__(*a, **kw)
        #: (monotonic arrival, "msg" | "ctl", text, MSGFLAG or 0)
        self.timeline: list[tuple[float, str, str, int]] = []

    def _handle(self, pkt_type, code, payload):
        nm, nc = len(self.messages), len(self.control)
        super()._handle(pkt_type, code, payload)
        now = time.monotonic()
        for i in range(nm, len(self.messages)):
            self.timeline.append((now, "msg", self.messages[i], self.message_flags[i]))
        for i in range(nc, len(self.control)):
            self.timeline.append((now, "ctl", self.control[i], 0))

    def stats(self) -> list[tuple[float, dict]]:
        out = []
        for t, kind, text, _f in list(self.timeline):
            if kind == "ctl":
                o = json.loads(text)
                if o.get("type") == "diag_stats":
                    out.append((t, o))
        return out

    def lines(self) -> list[tuple[float, str, int]]:
        return [(t, text, f) for t, kind, text, f in list(self.timeline)
                if kind == "msg" and text.startswith(_STATS_PREFIX)]


def _feed(fifo: Path, data: bytes, pieces: int, gap_s: float,
          hold: "threading.Event | None" = None, hold_s: float = 0.0,
          done: "dict | None" = None) -> threading.Thread:
    """Write `data` into the replay FIFO in `pieces`, `gap_s` apart, then hold
    the write end open (a quiet port) until `hold` is set or `hold_s` passes."""
    def run():
        with open(fifo, "wb") as w:
            step = max(1, -(-len(data) // pieces))
            for off in range(0, len(data), step):
                w.write(data[off:off + step])
                w.flush()
                if off + step < len(data):
                    time.sleep(gap_s)
            if done is not None:
                done["written"] = time.monotonic()
            if hold is not None:
                hold.wait(hold_s)
            elif hold_s > 0:
                time.sleep(hold_s)
    t = threading.Thread(target=run, daemon=True)
    t.start()
    return t


def _helper_words(lines) -> list[str]:
    """Stats lines that describe a helper process. There is none, so the
    readout must speak only of the decoder."""
    return [s for _t, s, _f in lines if "helper" in s.lower()]


