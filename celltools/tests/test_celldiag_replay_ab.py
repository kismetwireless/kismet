#: The tree's own replay fixture: four synthesised 0xB193 records, generated by
#: ``make_functional_fixture.py`` beside it, with their expected observations
#: pinned in ``functional.native.ndjson``.
_FIXTURES = Path(__file__).resolve().parents[2] / "capture_cell_diag" / "fixtures"
_FUNCTIONAL = _FIXTURES / "functional.hdlc"
_FUNCTIONAL_EXPECTED = _FIXTURES / "functional.native.ndjson"


def _fixture(tmp_path: Path) -> Path:
    """A private copy of the in-tree replay fixture.

    A copy, so a test that writes beside its replay (a rawlog= tee, a
    compressed twin) never touches the tree. Missing is a FAIL, not a skip: the
    fixture ships with the source, so its absence is a broken tree."""
    if not _FUNCTIONAL.is_file():
        pytest.fail(f"the in-tree replay fixture is missing: {_FUNCTIONAL}")
    dst = tmp_path / "replay.hdlc"
    shutil.copyfile(_FUNCTIONAL, dst)
    return dst


def _tiled_fixture(copies: int) -> bytes:
    """The in-tree fixture's four frames repeated ``copies`` times.

    For the tests that need a long or dense stream: ~545 bytes per
    observation, denser than most real captures. The fixture opens with one
    idle ``0x7E`` and closes every frame with another, so the repeats drop the
    leading flag and the stream stays one well-formed frame sequence."""
    if not _FUNCTIONAL.is_file():
        pytest.fail(f"the in-tree replay fixture is missing: {_FUNCTIONAL}")
    data = _FUNCTIONAL.read_bytes()
    assert data[:1] == b"\x7e", "the fixture no longer opens with an idle flag"
    return data[:1] + data[1:] * copies


def _decode_modes(run) -> set:
    return {json.loads(c).get("decode_mode") for c in run.control
            if '"diag_stats"' in c} - {None}


